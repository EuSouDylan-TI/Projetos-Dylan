    private void carregarTabela() {
        try {
            dao.SexualidadeDao dao = new dao.SexualidadeDao();

            java.util.ArrayList<modelo.Sexualidade> lista = dao.consultarAtivas();
            javax.swing.table.DefaultTableModel modeloTabela =
                (javax.swing.table.DefaultTableModel) TbSexualidade.getModel();

            modeloTabela.setRowCount(0);

            for (modelo.Sexualidade sexualidade : lista) {
                modeloTabela.addRow(new Object[]{
                    sexualidade.getId(),
                    sexualidade.getDescricao(),
                    sexualidade.getSigla(),
                    sexualidade.getStatus()
                });
            }

        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar os registros: " + ex.getMessage()
            );
        }
    }
