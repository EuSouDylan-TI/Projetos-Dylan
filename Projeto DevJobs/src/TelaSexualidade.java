    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        
String id = txtId.getText().trim();
String descricao = txtDescricao.getText().trim();
String sigla = txtSigla.getText().trim();

if (id.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Selecione um cadastro para alterar."
    );
    return;
}

if (descricao.isEmpty() || sigla.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Preencha a descrição e a sigla."
    );
    return;
}

try {
    modelo.Sexualidade sexualidade = new modelo.Sexualidade();

    sexualidade.setId(Integer.parseInt(id));
    sexualidade.setDescricao(descricao);
    sexualidade.setSigla(sigla);
    sexualidade.setStatus(cbStatus.getSelectedItem().toString());

    dao.SexualidadeDao dao = new dao.SexualidadeDao();
    dao.alterar(sexualidade);

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Cadastro alterado com sucesso!"
    );

    carregarTabela();

    txtId.setText("");
    txtDescricao.setText("");
    txtSigla.setText("");
    cbStatus.setSelectedIndex(0);

} catch (Exception ex) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Erro ao alterar: " + ex.getMessage()
    );
}

    }//GEN-LAST:event_btnAlterarActionPerformed

    private void TbSexualidadeMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TbSexualidadeMouseClicked
        
int linha = TbSexualidade.getSelectedRow();

if (linha >= 0) {
    txtId.setText(
        TbSexualidade.getValueAt(linha, 0).toString()
    );

    txtDescricao.setText(
        TbSexualidade.getValueAt(linha, 1).toString()
    );

    txtSigla.setText(
        TbSexualidade.getValueAt(linha, 2).toString()
    );

    cbStatus.setSelectedItem(
        TbSexualidade.getValueAt(linha, 3).toString()
    );
}

    }//GEN-LAST:event_TbSexualidadeMouseClicked

